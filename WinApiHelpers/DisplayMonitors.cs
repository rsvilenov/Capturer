        }

        public static DisplayMonitor GetByWindowHandle(IntPtr hWnd)
        {
            var hMonitor = MonitorFromWindow(hWnd, MONITOR_DEFAULTTONEAREST);
            return _allMonitors.First(mon => mon.Handle == hMonitor);
        }

        private static void Load()
        {
            int monitorNum = 0;
            var monitorFriendlyNames = GetAllMonitorsFriendlyNames();

            var taskbarWindows = Windows.GetWindowsByClassName("Shell_TrayWnd").
                Union(Windows.GetWindowsByClassName("Shell_SecondaryTrayWnd"));

            MonitorEnumProc callback = (IntPtr hDesktop, IntPtr hdc, ref Rect prect, int d) =>
            {
                var bounds = new Rectangle
                {
                    X = prect.left,
                    Y = prect.top,
                    Width = prect.right - prect.left,
                    Height = prect.bottom - prect.top
                };

                var dpi = DPIHelper.GetDPIForScreen(hDesktop);

                MonitorInfoEx monInfo = new MonitorInfoEx();
                monInfo.Init();
                monInfo.Size = (uint)Marshal.SizeOf(monInfo);
                bool success = GetMonitorInfo(hDesktop, ref monInfo);
                if (!success)
                {
                    throw new Win32Exception("GetMonitorInfo failed.");
                }

                var workingArea = new Rectangle
                {
                    X = monInfo.WorkArea.left,
                    Y = monInfo.WorkArea.top,
                    Width = monInfo.WorkArea.right - monInfo.WorkArea.left,
                    Height = monInfo.WorkArea.bottom - monInfo.WorkArea.top
                };

                var taskbarWindowRect = taskbarWindows.Select(tbw => tbw.Value).
                FirstOrDefault(rct => bounds.Contains(rct));
                var taskbarPosition = DisplayMonitor.TaskbarPosition.NoTaskbar;
                if (taskbarWindowRect != null)
                {
                    taskbarPosition = CalibrateWorkingAreaAccordingToTaskbarPosition(bounds, taskbarWindowRect, ref workingArea);
                }

                bool isPrimary = monInfo.Flags == 1;
                string fiendlyName = monitorFriendlyNames.ElementAt(monitorNum++);
                _allMonitors.Add(new DisplayMonitor(hDesktop, monInfo.DeviceName, fiendlyName, bounds, workingArea, dpi, isPrimary, taskbarPosition));

                return true;
            };

            EnumDisplayMonitors(IntPtr.Zero, IntPtr.Zero, callback, 0);
        }

        private static DisplayMonitor.TaskbarPosition CalibrateWorkingAreaAccordingToTaskbarPosition(Rectangle boulds, Rectangle taskbarWindowRect, ref Rectangle workingArea)
        {
            if (taskbarWindowRect.X == boulds.X &&
                                    taskbarWindowRect.Width == boulds.Width &&
                                    taskbarWindowRect.Y == boulds.Y)
            {
                // the taskbar is at the top
                workingArea.Y = taskbarWindowRect.Height;
                return DisplayMonitor.TaskbarPosition.Top;
            }
            else if (taskbarWindowRect.X == boulds.X &&
                taskbarWindowRect.Width == boulds.Width &&
                taskbarWindowRect.Y > boulds.Y)
            {
                // the taskbar is at the bottom
                workingArea.Height = taskbarWindowRect.Top;
                return DisplayMonitor.TaskbarPosition.Bottom;
            }
            else if (taskbarWindowRect.X == boulds.X && taskbarWindowRect.Y == boulds.Y)
            {
                // the taskbar is at the left side
                workingArea.X = taskbarWindowRect.Width;
                return DisplayMonitor.TaskbarPosition.Left;
            }
            else if (taskbarWindowRect.X > boulds.X && taskbarWindowRect.Y == boulds.Y)
            {
                // the taskbar is at the right side
                workingArea.Width = taskbarWindowRect.X;
                return DisplayMonitor.TaskbarPosition.Right;
            }

            return DisplayMonitor.TaskbarPosition.NoTaskbar;
        }

        public static void Reload()
        {
            lock (_allMonitors)
            {
                _allMonitors.Clear();
                Load();
            }
        }

